package com.followfollowme.bosspickseoul.domainlayer.district.adapter.out.persistence.repository;

import static org.assertj.core.api.Assertions.assertThat;

import com.followfollowme.bosspickseoul.domainlayer.district.adapter.out.persistence.entity.PensionIncomeDistrictEntity;
import com.followfollowme.bosspickseoul.global.config.CommercialDataJpaTest;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.Optional;
import javax.sql.DataSource;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;

/**
 * 「요청 분기 말일 이하 최신 기준일」을 고르는 파생 쿼리를 실제 스키마에서 확인한다. (이슈 #415)
 *
 * <p>파생 쿼리는 메서드 이름이 계약이라 프로퍼티명 하나가 틀려도 컴파일은 통과하고 리포지터리 빈을 만들 때 터진다. 그리고
 * 「이하」·「최신」·「자치구별」 의미는 DB 가 정하므로 목으로는 확인할 수 없다.
 *
 * <p>테이블은 batch-service 가 런북으로 만든다. 그래서 이 슬라이스도 Hibernate 가 만들어 주지 않는다 — 스키마 필터가 빼기
 * 때문이고, {@link #createBatchOwnedTable()} 이 먼저 그것을 확인한다. 아래 DDL 은 런북
 * ({@code scripts/migration/pension-income-district-table.sql})을 H2 문법으로 옮긴 것이고, 컬럼 이름·길이·NOT NULL 이
 * 런북과 같은지는 {@code PensionIncomeDistrictSchemaContractTest} 가 엔티티와 런북을 직접 대조한다.
 */
@CommercialDataJpaTest
class PensionIncomeDistrictRepositoryTest {

    private static final String JONGNO = "11110";
    private static final String GANGNAM = "11680";

    private static final String CREATE_TABLE = """
        CREATE TABLE pension_income_district (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            reference_date DATE NOT NULL,
            district_code VARCHAR(5) NOT NULL,
            district_name VARCHAR(10) NOT NULL,
            source_region_name VARCHAR(64) NOT NULL,
            average_monthly_income_amount BIGINT NOT NULL,
            source_updated_at TIMESTAMP(6) NOT NULL,
            source_checksum CHAR(64) NOT NULL,
            run_id VARCHAR(64) NOT NULL,
            loaded_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP(6) NOT NULL,
            CONSTRAINT uk_pension_income_district_district_code_reference_date UNIQUE (district_code, reference_date)
        )
        """;

    private static final String INSERT_ROW = """
        INSERT INTO pension_income_district (
            reference_date, district_code, district_name, source_region_name, average_monthly_income_amount,
            source_updated_at, source_checksum, run_id
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?)
        """;

    @Autowired
    private DataSource dataSource;

    @Autowired
    private PensionIncomeDistrictRepository pensionIncomeDistrictRepository;

    private JdbcTemplate jdbcTemplate;

    @BeforeEach
    void createBatchOwnedTable() {
        jdbcTemplate = new JdbcTemplate(dataSource);
        // 필터가 빠지면 ddl-auto 가 엔티티 모양으로 이 테이블을 먼저 만든다. 스키마 초기화가 끝난 지금 없어야 한다.
        assertThat(tableExists()).as("ddl-auto 가 배치 소유 테이블 pension_income_district 를 만들었다").isFalse();

        jdbcTemplate.execute(CREATE_TABLE);
        // 원본 2020-12 ~ 2024-12 의 종로구 다섯 해와 강남구 마지막 해.
        insert(JONGNO, "종로구", LocalDate.of(2020, 12, 31), 1_478_370L);
        insert(JONGNO, "종로구", LocalDate.of(2021, 12, 31), 1_495_060L);
        insert(JONGNO, "종로구", LocalDate.of(2022, 12, 31), 1_526_707L);
        insert(JONGNO, "종로구", LocalDate.of(2023, 12, 31), 1_547_465L);
        insert(JONGNO, "종로구", LocalDate.of(2024, 12, 31), 1_555_244L);
        insert(GANGNAM, "강남구", LocalDate.of(2024, 12, 31), 1_799_199L);
    }

    @AfterEach
    void dropBatchOwnedTable() {
        jdbcTemplate.execute("DROP TABLE IF EXISTS pension_income_district");
    }

    @ParameterizedTest(name = "말일 {0} -> 기준일 {1}")
    @CsvSource({
        "2021-03-31, 2020-12-31, 1478370",
        "2024-12-31, 2024-12-31, 1555244",
        "2026-03-31, 2024-12-31, 1555244"
    })
    @DisplayName("분기 말일 이하에서 가장 최근 기준일 한 행을 고른다 (20211 / 20244 / 20261)")
    void findsLatestReferenceDateOnOrBeforeQuarterEnd(LocalDate quarterEnd, LocalDate expectedReferenceDate, long expectedAmount) {
        Optional<PensionIncomeDistrictEntity> found = pensionIncomeDistrictRepository
            .findFirstByDistrictCodeAndReferenceDateLessThanEqualOrderByReferenceDateDesc(JONGNO, quarterEnd);

        assertThat(found).hasValueSatisfying(entity -> {
            assertThat(entity.getReferenceDate()).isEqualTo(expectedReferenceDate);
            assertThat(entity.getAverageMonthlyIncomeAmount()).isEqualTo(expectedAmount);
            assertThat(entity.getDistrictName()).isEqualTo("종로구");
            assertThat(entity.getSourceRegionName()).isEqualTo("서울특별시종로구");
        });
    }

    @Test
    @DisplayName("분기 말일 이전 기준일이 없으면 미래 기준일을 끌어오지 않고 비운다")
    void returnsEmptyWhenNothingOnOrBeforeQuarterEnd() {
        assertThat(pensionIncomeDistrictRepository
            .findFirstByDistrictCodeAndReferenceDateLessThanEqualOrderByReferenceDateDesc(JONGNO, LocalDate.of(2020, 9, 30)))
            .isEmpty();
    }

    @Test
    @DisplayName("다른 자치구 행은 섞이지 않는다")
    void neverMixesInAnotherDistrict() {
        assertThat(pensionIncomeDistrictRepository
            .findFirstByDistrictCodeAndReferenceDateLessThanEqualOrderByReferenceDateDesc(GANGNAM, LocalDate.of(2026, 3, 31)))
            .hasValueSatisfying(entity -> assertThat(entity.getAverageMonthlyIncomeAmount()).isEqualTo(1_799_199L));
        assertThat(pensionIncomeDistrictRepository
            .findFirstByDistrictCodeAndReferenceDateLessThanEqualOrderByReferenceDateDesc(GANGNAM, LocalDate.of(2023, 12, 31)))
            .isEmpty();
    }

    private void insert(String districtCode, String districtName, LocalDate referenceDate, long amount) {
        jdbcTemplate.update(INSERT_ROW, referenceDate, districtCode, districtName, "서울특별시" + districtName, amount,
            LocalDateTime.of(2025, 1, 31, 0, 0), "a".repeat(64), "pension-income-test");
    }

    private boolean tableExists() {
        Integer count = jdbcTemplate.queryForObject(
            "SELECT COUNT(*) FROM INFORMATION_SCHEMA.TABLES WHERE UPPER(TABLE_NAME) = 'PENSION_INCOME_DISTRICT'", Integer.class);
        return count != null && count > 0;
    }
}
