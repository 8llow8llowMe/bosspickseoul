import { readFile, mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

const [inputPath, outputPath] = process.argv.slice(2)

if (!inputPath || !outputPath) {
  throw new Error(
    'Usage: node scripts/generate-status-map.mjs <input-geojson> <output-ts>',
  )
}

const width = 800
const height = 620
const round = value => Math.round(value * 100) / 100
const formatNumber = value => String(round(value))

const geoJson = JSON.parse(await readFile(inputPath, 'utf8'))

if (!Array.isArray(geoJson.features)) {
  throw new Error('GeoJSON FeatureCollection with features is required.')
}

function getPolygons(geometry) {
  if (geometry?.type === 'Polygon') {
    return [geometry.coordinates]
  }

  if (geometry?.type === 'MultiPolygon') {
    return geometry.coordinates
  }

  return []
}

const features = geoJson.features.map(feature => {
  const code = feature.properties?.SIG_CD
  const polygons = getPolygons(feature.geometry)

  if (!code || polygons.length === 0) {
    throw new Error(
      'Every feature must include properties.SIG_CD and Polygon geometry.',
    )
  }

  return { code, polygons }
})

const positions = features.flatMap(({ polygons }) =>
  polygons.flatMap(polygon => polygon.flat()),
)

const longitudes = positions.map(([longitude]) => longitude)
const latitudes = positions.map(([, latitude]) => latitude)
const minLongitude = Math.min(...longitudes)
const maxLongitude = Math.max(...longitudes)
const minLatitude = Math.min(...latitudes)
const maxLatitude = Math.max(...latitudes)

if (minLongitude === maxLongitude || minLatitude === maxLatitude) {
  throw new Error('GeoJSON bounds must have non-zero width and height.')
}

function project([longitude, latitude]) {
  return [
    round(((longitude - minLongitude) / (maxLongitude - minLongitude)) * width),
    round(((maxLatitude - latitude) / (maxLatitude - minLatitude)) * height),
  ]
}

function createPath(polygons) {
  return polygons
    .flatMap(polygon => polygon)
    .map(ring => {
      const [firstPoint, ...remainingPoints] = ring.map(project)
      const commands = [
        `M${formatNumber(firstPoint[0])} ${formatNumber(firstPoint[1])}`,
        ...remainingPoints.map(
          point => `L${formatNumber(point[0])} ${formatNumber(point[1])}`,
        ),
      ]

      return `${commands.join(' ')}Z`
    })
    .join(' ')
}

function createCenter(polygons) {
  const outerRingPoints = polygons.flatMap(polygon => polygon[0].map(project))
  const xCoordinates = outerRingPoints.map(([x]) => x)
  const yCoordinates = outerRingPoints.map(([, y]) => y)

  return {
    x: round((Math.min(...xCoordinates) + Math.max(...xCoordinates)) / 2),
    y: round((Math.min(...yCoordinates) + Math.max(...yCoordinates)) / 2),
  }
}

const paths = features.map(({ polygons }) => createPath(polygons))
const centers = Object.fromEntries(
  features.map(({ code, polygons }) => [code, createCenter(polygons)]),
)
const source = `// Generated by scripts/generate-status-map.mjs. Do not edit manually.\n\nexport const SEOUL_STATUS_VIEW_BOX = '0 0 800 620'\n\nexport const SEOUL_STATUS_PATHS = [\n${paths.map(mapPath => `  '${mapPath}',`).join('\n')}\n] as const\n\nexport const SEOUL_DISTRICT_CENTERS: Record<string, { x: number; y: number }> =\n  {\n${Object.entries(
  centers,
)
  .map(([code, center]) => `    '${code}': { x: ${center.x}, y: ${center.y} },`)
  .join('\n')}\n  }\n`

await mkdir(path.dirname(path.resolve(outputPath)), { recursive: true })
await writeFile(outputPath, source)
